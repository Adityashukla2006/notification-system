        rows = [psql_rows(f.replace(".queue.txt", ".idempotency.txt"), "total rows") for f in fs]
        p(f"| {tag} | 1 key × 1,000 concurrent copies | "
          f"{med([num(r[0]['total_rows']) if r else None for r in rows])} | "
          f"{med([num(kv(f, 'LLEN notifications:queue')) for f in fs])} | "
          f"(LLEN = rows, so none) | {len(fs)} |")

