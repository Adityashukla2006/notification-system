p()
p("## Exactly-one-enqueue (workers stopped, so every push stays on the queue)")
p()
p("| Build | Test | Rows | Queue entries (LLEN) | IDs pushed >1 time | Reps |")
p("|---|---|---|---|---|---|")
for tag in ("before", "latest"):
    fs = reps(f"pilot_clean/enqueue-{tag}/keys*-r*.queue.txt")
    if fs:
        p(f"| {tag} | 5,000 keys × 5 concurrent copies | "
          f"{med([num(kv(f, 'notification rows')) for f in fs])} | "
          f"{med([num(kv(f, 'LLEN notifications:queue (every push)')) for f in fs])} | "
          f"{med([num(kv(f, 'ids pushed more than once')) for f in fs])} | {len(fs)} |")
    # Single-key runs (earlier, results/enqueue-*): only LLEN is valid there;
    # their "distinct ids" line came from a broken tr and is not reported.
    fs = reps(f"enqueue-{tag}/dups*-r*.queue.txt")
