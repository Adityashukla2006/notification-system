# ---------------------------------------------------------------- 1. ingest
INGEST_MEASURE_S = 30  # bench/run.sh INGEST_DURATION
steps = {}
for f in reps("ingest/rate*-r*.k6.json"):
    rate = int(re.search(r"rate(\d+)-r", f).group(1))
    m = k6(f)
    # Use the measured window ({scenario:load}) when the run had a warm-up.
    # Its "rate" divides by the whole test including warm-up, so achieved
    # req/s is recomputed as count / INGEST_MEASURE_S.
    if "http_reqs{scenario:load}" in m:
        m = {
            "http_reqs": {"count": m["http_reqs{scenario:load}"]["count"],
                          "rate": m["http_reqs{scenario:load}"]["count"] / INGEST_MEASURE_S},
            "http_req_duration": m["http_req_duration{scenario:load}"],
            "http_req_failed": m["http_req_failed{scenario:load}"],
            "dropped_iterations": m["dropped_iterations{scenario:load}"],
        }
    steps.setdefault(rate, []).append(m)
if steps:
    p()
    p("## 1. Ingestion (open-loop fixed rate; 10 s warm-up then 30 s measured per step; 4 tenants; workers stopped)")
    p()
    p("Pass = error rate < 1% AND dropped iterations < 1% of offered AND p99 ≤ 100 ms (set before the runs).")
    p()
    p("| Offered req/s | Achieved req/s | p50 ms | p95 ms | p99 ms | Error % | Dropped % | Reps passing |")
    p("|---|---|---|---|---|---|---|---|")
    best = {}
    for rate in sorted(steps):
        ms = steps[rate]
        passing = 0
        for n, m in enumerate(ms):
            offered = m["http_reqs"]["count"] + m.get("dropped_iterations", {}).get("count", 0)
            drop = m.get("dropped_iterations", {}).get("count", 0) / offered
            ok = m["http_req_failed"]["value"] < 0.01 and drop < 0.01 and m["http_req_duration"]["p(99)"] <= 100
            passing += ok
            if ok:
                best.setdefault(n, []).append((rate, m))
        p(f"| {rate} | {med([m['http_reqs']['rate'] for m in ms])} | "
          f"{med([m['http_req_duration']['med'] for m in ms])} | "
          f"{med([m['http_req_duration']['p(95)'] for m in ms])} | "
          f"{med([m['http_req_duration']['p(99)'] for m in ms])} | "
          f"{med([100 * m['http_req_failed']['value'] for m in ms])} | "
          f"{med([100 * m.get('dropped_iterations', {}).get('count', 0) / (m['http_reqs']['count'] + m.get('dropped_iterations', {}).get('count', 0)) for m in ms])} | "
          f"{passing}/{len(ms)} |")
    tops = [max(v, key=lambda x: x[0])[0] for v in best.values()]
    if tops:
        sustained = statistics.median_low(tops)
        at = steps[sustained]
        p()
        p(f"Highest passing step per rep: {', '.join(str(t) for t in tops)} req/s; "
          f"max sustained (median of reps) = **{sustained} req/s**. "
          f"At {sustained} req/s across all {len(at)} reps: "
          f"p50 {med([m['http_req_duration']['med'] for m in at])} ms, "
          f"p95 {med([m['http_req_duration']['p(95)'] for m in at])} ms, "
          f"p99 {med([m['http_req_duration']['p(99)'] for m in at])} ms.")

# ---------------------------------------------------------------- 3. scaling
sc = {}
for f in reps("scaling/i*-r*.throughput.txt"):
    sc.setdefault(int(re.search(r"/i(\d+)-r", f.replace("\\", "/")).group(1)), []).append(f)
if sc:
    p()
    p("## 3. Worker scaling (20,000-notification backlog, 10 slots per instance, 1 CPU each, provider 50±25 ms)")
    p()
    p("| Instances | Slots | Delivered/s | Drain window s | Speed-up vs 1 | Ideal | Efficiency | Reps |")
    p("|---|---|---|---|---|---|---|---|")
    base = None
    for n in sorted(sc):
        tp = [num(psql_rows(f, "== throughput")[0]["delivered_per_s"]) for f in sc[n]]
        win = [num(psql_rows(f, "== throughput")[0]["window_s"]) for f in sc[n]]
        m = statistics.median(tp)
        base = base or m
        p(f"| {n} | {n * 10} | {med(tp)} | {med(win)} | {m / base:.2f}× | {n}× | {100 * m / base / n:.0f}% | {len(tp)} |")

