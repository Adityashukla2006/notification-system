    p("|---|---|---|---|---|---|---|---|")
    for mode in ("baseline", "unlimited", "limited"):
        if mode not in fa:
            continue
        q, nz_acc, nz_req = [], [], []
        for f in fa[mode]:
            byt = {r["tenant"]: r for r in psql_rows(f, "e2e latency by tenant")}
            q.append(byt.get("bench-tenant-1"))
            nz_acc.append(num(byt["bench-tenant-0"]["n"]) if "bench-tenant-0" in byt else 0)
            m = k6(f.replace(".latency.txt", ".k6.json"))
            nz_req.append(m.get("http_reqs{tenant:0}", {}).get("count", 0))
        p(f"| {mode} | {med([num(x['p50']) for x in q])} | {med([num(x['p95']) for x in q])} | "
          f"{med([num(x['p99']) for x in q])} | {med([num(x['max']) for x in q])} | {med(nz_acc)} | {med(nz_req)} | {len(q)} |")

