    p("|---|---|---|---|---|---|---|")
    for f in bu:
        t = psql_rows(f, "== throughput")[0]
        m = k6(f.replace(".throughput.txt", ".k6.json"))
        rows = [l.split("\t") for l in open(f.replace(".throughput.txt", ".queue.tsv"), encoding="utf-8").read().splitlines()[1:] if l.count("\t") == 3]
        peak = max(int(r[1]) for r in rows) if rows else None
        v = psql_rows(f.replace(".throughput.txt", ".verify.txt"), "accepted ids vs notifications")[0]
        dur = m["http_reqs"]["count"] / m["http_reqs"]["rate"]
        p(f"| {re.search(r'-r(\d+)', f).group(1)} | {dur:.1f} | {m['http_reqs']['rate']:.0f} | {peak} | "
          f"{t['drain_from_first_created_s']} | {t['delivered']} | {int(num(v['accepted_without_row']) + num(v['not_terminal']))} |")

