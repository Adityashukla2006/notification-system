"""Build bench/results/summary.md from the raw outputs under bench/results/.

Every number printed here is read from a file a run wrote: k6's JSON summary
(*.k6.json) or the saved psql output of bench/sql/*.sql (*.<query>.txt). Across
repetitions it reports the median and the spread (min-max). Nothing is
estimated, extrapolated, or rounded beyond one decimal place.

Usage: python bench/summarize.py
"""

import glob
import json
import os
import re
import statistics
import sys

sys.stdout.reconfigure(encoding="utf-8")

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
out = []


def p(line=""):
    out.append(line)


def k6(path):
    return json.load(open(path, encoding="utf-8"))["metrics"]


def psql_rows(path, marker):
    """Rows (dicts) of the first psql table after the line containing marker."""
    lines = open(path, encoding="utf-8").read().splitlines()
    i = next((n for n, l in enumerate(lines) if marker in l), None)
    if i is None:
        return []
    # A psql table is: header line, a line of dashes, data lines, blank line.
    # Single-column tables have no "|", so find the dash line instead.
    j = i + 1
    while j + 1 < len(lines) and not re.fullmatch(r"-+(\+-+)*", lines[j + 1].strip()):
        j += 1
    if j + 1 >= len(lines):
        return []
    header = [h.strip() for h in lines[j].split("|")]
    rows = []
    for l in lines[j + 2:]:
        if not l.strip() or l.startswith("=="):
            break
        rows.append(dict(zip(header, [c.strip() for c in l.split("|")])))
    return rows


def kv(path, key):
    """Value of a 'key = value' line."""
    for l in open(path, encoding="utf-8"):
        if l.startswith(key + " ="):
            return l.split("=", 1)[1].strip()
    return None


def num(x):
    return float(x) if x not in (None, "") else None


def med(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "n/a"
    m = statistics.median(xs)
    lo, hi = min(xs), max(xs)
    f = (lambda v: f"{v:.0f}") if max(abs(v) for v in xs) >= 100 else (lambda v: f"{v:.1f}")
    return f"{f(m)} ({f(lo)}–{f(hi)})" if len(xs) > 1 else f(m)


def reps(pattern):
    return sorted(glob.glob(os.path.join(RES, pattern)))


def one(path, query, marker, col):
    f = path.replace(".k6.json", f".{query}.txt")
    rows = psql_rows(f, marker) if os.path.exists(f) else []
    return num(rows[0][col]) if rows else None


