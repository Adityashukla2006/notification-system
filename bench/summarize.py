# ---------------------------------------------------------------- 5. crash
cr = reps("crash/kill-r*.recovery.txt")
if cr:
    p()
    p("## 5. Crash recovery (kill -9 one of 2 workers × 10 slots at 30 s into a 200 req/s, 90 s load; restarted)")
    p()
    p("Times come from Docker's State.FinishedAt / State.StartedAt and Postgres, all on the Docker VM clock.")
    p()
    p("| Rep | Accepted | Delivered | Lost | In-flight at kill | Of those delivered | Down s (death → restart) | Recovery s from death | Recovery s from restart | IDs sent >1 time (ledger) |")
    p("|---|---|---|---|---|---|---|---|---|---|")
    from datetime import datetime
    def ts(f, key):
        for l in open(f, encoding="utf-8"):
            if key in l:
                v = l.split(": ", 1)[1].strip().rstrip("Z")
                return datetime.fromisoformat(v[:26])
    for f in cr:
        r = psql_rows(f, "fate of every in-flight id")[0]
        v = f.replace(".recovery.txt", ".verify.txt")
        acc = psql_rows(v, "accepted ids vs notifications")[0]
        dup = psql_rows(v, "provider ledger")[0]
        lost = int(num(acc["accepted_without_row"]) + num(acc["not_terminal"]))
        down = (ts(f, "State.StartedAt") - ts(f, "State.FinishedAt")).total_seconds()
        p(f"| {re.search(r'r(\d+)', os.path.basename(f)).group(1)} | {acc['distinct_accepted_ids']} | {acc['delivered']} | {lost} | "
          f"{r['inflight_ids']} | {r['delivered']} | {down:.2f} | {r['recovery_s_from_kill']} | {r['recovery_s_from_restart']} | "
          f"{dup['ids_sent_more_than_once']} |")

